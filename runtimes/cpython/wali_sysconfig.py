"""Turn the cross build's _sysconfigdata into the one the GUEST should see.

`make pybuilddir.txt` writes build_time_vars describing THIS build machine: CC is the
host's LLVM with a host --sysroot, LDFLAGS name host directories. Inside walios the
compiler is the in-tab `cc` wrapper (walios/bin/cc), which already supplies the WALI
target, /sysroot and the wasm feature flags itself, so a package built with pip or
setuptools must be handed `cc`, not a path that does not exist there.

    python3 wali_sysconfig.py <generated _sysconfigdata*.py> <out.py> <build root>

Fails if any host path survives, so a new variable that leaks one is noticed.
"""
import pprint
import runpy
import sys

src, out, root = sys.argv[1], sys.argv[2], sys.argv[3].rstrip('/')
v = runpy.run_path(src)['build_time_vars']

TOOLS = {
    'CC': 'cc', 'CXX': 'cc', 'LINKCC': 'cc', 'MAINCC': 'cc', 'CPP': 'cc -E',
    'LDSHARED': 'cc -shared', 'BLDSHARED': 'cc -shared', 'LDCXXSHARED': 'cc -shared',
    'AR': 'ar', 'RANLIB': 'ranlib', 'READELF': 'true',
    'CFLAGS': '-DNDEBUG -O2 -Wall', 'OPT': '-DNDEBUG -O2 -Wall', 'CFLAGS_NODIST': '',
    'CONFIGURE_CFLAGS': '', 'CONFIGURE_LDFLAGS': '', 'CONFIGURE_CPPFLAGS': '',
    'LDFLAGS': '', 'LDFLAGS_NODIST': '', 'PY_LDFLAGS': '', 'PY_LDFLAGS_NODIST': '',
    'CPPFLAGS': '', 'LINKFORSHARED': '', 'CCSHARED': '-fPIC',
    'HOST_GNU_TYPE': 'wasm32-unknown-linux-muslwali',   # the target triple cc really uses
}
for k, val in TOOLS.items():
    if k in v:
        v[k] = val

llvm_bin = None
for k, val in v.items():
    if isinstance(val, str) and '/bin/clang' in val:
        llvm_bin = val.split('/bin/clang')[0] + '/bin/'
        break
for k, val in list(v.items()):
    if not isinstance(val, str):
        continue
    if llvm_bin:
        val = val.replace(llvm_bin, '')
    val = val.replace(root + '/sysroot', '/sysroot').replace(root + '/cross-py', '/py').replace(root, '/py')
    v[k] = val

leaks = sorted(k for k, val in v.items() if isinstance(val, str) and '/home/' in val)
if leaks:
    sys.exit('host paths left in: ' + ', '.join(leaks))
with open(out, 'w') as f:
    f.write('# system configuration of the walios CPython (generated by walios/build/cpython)\n')
    f.write('build_time_vars = ')
    pprint.pprint(v, stream=f)
print('wrote', out, len(v), 'vars')

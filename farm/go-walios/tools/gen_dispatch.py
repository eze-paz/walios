import json, sys
tab = json.load(open(__import__('os').path.join(__import__('os').path.dirname(__import__('os').path.abspath(__file__)), 'wali-table.json')))
out = []
w = out.append
w('// Code generated by gen_dispatch.py from the WALI syscall spec; DO NOT EDIT.\n')
w('//go:build linux && wasm\n')
w('package linux\n')
w('// Syscall6 for linux/wasm on a WALI kernel (walios): each Linux syscall is the')
w('// host import wali.SYS_<name>, typed like the C prototype (pointers, int and size_t')
w('// are i32; long, off_t and other 8-byte types are i64). The result is the raw')
w('// kernel return: -errno on failure.\n')
for name, nr, k in tab:
    params = ', '.join('a%d %s' % (i, 'int64' if c == 'L' else 'int32') for i, c in enumerate(k))
    w('//go:wasmimport wali SYS_%s' % name)
    w('func wali_%s(%s) int64\n' % (name, params))
w('// nosplit: syscall.RawSyscall6 (nosplit) calls it, so it must not grow the stack.')
w('//')
w('//go:nosplit')
w('func Syscall6(num, a1, a2, a3, a4, a5, a6 uintptr) (r1, r2, errno uintptr) {')
w('\tvar r int64')
w('\tswitch num {')
for name, nr, k in tab:
    args = ', '.join(('int64(a%d)' if c == 'L' else 'int32(a%d)') % (i + 1) for i, c in enumerate(k))
    w('\tcase %d: // %s' % (nr, name))
    w('\t\tr = wali_%s(%s)' % (name, args))
w('\tdefault:')
w('\t\treturn ^uintptr(0), 0, 38 // ENOSYS: not a WALI syscall')
w('\t}')
w('\tif r < 0 && r > -4096 {')
w('\t\treturn ^uintptr(0), 0, uintptr(-r)')
w('\t}')
w('\treturn uintptr(r), 0, 0')
w('}')
open(sys.argv[1], 'w', encoding='utf-8', newline='').write('\n'.join(out) + '\n')
print(len(tab), 'syscalls')
